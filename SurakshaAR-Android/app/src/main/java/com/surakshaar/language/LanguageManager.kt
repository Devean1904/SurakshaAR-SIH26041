package com.surakshaar.language

import android.content.Context
import android.content.SharedPreferences

object LanguageManager {

    private const val PREFS_NAME = "surakshaar_language"
    private const val KEY_CURRENT_LANG = "current_language"

    private lateinit var prefs: SharedPreferences
    private var currentLanguage: String = "sat"

    private val translations = HashMap<String, HashMap<String, String>>()

    fun init(context: Context) {
        prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        currentLanguage = prefs.getString(KEY_CURRENT_LANG, "sat") ?: "sat"
        loadTranslations()
    }

    fun setLanguage(langCode: String) {
        if (langCode in getSupportedLanguages()) {
            currentLanguage = langCode
            prefs.edit().putString(KEY_CURRENT_LANG, langCode).apply()
        }
    }

    fun get(key: String): String {
        val langMap = translations[key]
        if (langMap != null) {
            langMap[currentLanguage]?.let { return it }
            langMap["en"]?.let { return it }
        }
        return key
    }

    fun getCurrentLanguage(): String = currentLanguage

    fun getSupportedLanguages(): Array<String> =
        arrayOf("sat", "hi", "en", "mr", "ta", "te", "kn")

    fun getLanguageName(langCode: String): String = when (langCode) {
        "en" -> "English"
        "hi" -> "हिन्दी (Hindi)"
        "sat" -> "ᱥᱟᱱᱛᱟᱞᱤ (Santali)"
        "mr" -> "मराठी (Marathi)"
        "ta" -> "தமிழ் (Tamil)"
        "te" -> "తెలుగు (Telugu)"
        "kn" -> "ಕನ್ನಡ (Kannada)"
        else -> langCode
    }

